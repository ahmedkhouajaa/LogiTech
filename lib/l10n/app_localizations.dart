  String tr(String key) {
    if (key.isEmpty) return key;

    final lang = locale.languageCode;
    final dict = _localizedValues[lang] ?? _localizedValues['fr']!;

    if (dict.containsKey(key)) {
      return dict[key]!;
    }

    // Direct check for trailing ellipsis like "Sélectionner un article..." or "Rechercher..."
    if (key.trim().endsWith('...')) {
      final base = key.trim().substring(0, key.trim().length - 3).trim();
      final translatedBase = tr(base);
      if (translatedBase != base) {
        return '$translatedBase...';
      }
    } else if (key.trim().endsWith('…')) {
      final base = key.trim().substring(0, key.trim().length - 1).trim();
      final translatedBase = tr(base);
      if (translatedBase != base) {
        return '$translatedBase…';
      }
    }

    // Try without accents / normalized
    final normKey = _normalize(key);
    for (final entry in dict.entries) {
      if (_normalize(entry.key) == normKey) {
        if (key.trim().endsWith('...') && !entry.value.endsWith('...')) {
          return '${entry.value}...';
        }
        return entry.value;
      }
    }

    // Check for trailing asterisk (required indicator) like "Nom *" or "Nom*"
    if (key.trim().endsWith('*')) {
      final base = key.trim().substring(0, key.trim().length - 1).trim();
      final translatedBase = tr(base);
      if (translatedBase != base) {
        return '$translatedBase *';
      }
    }

    // Check for trailing colon like "Date:" or "Date :"
    if (key.trim().endsWith(':')) {
      final base = key.trim().substring(0, key.trim().length - 1).trim();
      final translatedBase = tr(base);
      if (translatedBase != base) {
        return lang == 'ar' ? '$translatedBase:' : '$translatedBase :';
      }
    }

    // Fallback: if key doesn't have ellipsis but dict has key + '...'
    if (dict.containsKey('$key...')) {
      final val = dict['$key...']!;
      if (val.endsWith('...')) {
        return val.substring(0, val.length - 3).trim();
      }
      return val;
    }

    // Fallback: if English and not found, check French or return key
    return key;
  }

  static String _normalize(String s) {
    return s
        .toLowerCase()
        .replaceAll(RegExp(r'[éèêë]'), 'e')
        .replaceAll(RegExp(r'[àâä]'), 'a')
        .replaceAll(RegExp(r'[îï]'), 'i')
        .replaceAll(RegExp(r'[ôö]'), 'o')
        .replaceAll(RegExp(r'[ûüù]'), 'u')
        .replaceAll(RegExp(r'[ç]'), 'c')
        .replaceAll(RegExp(r'[\.…]'), '')
        .trim();
  }
